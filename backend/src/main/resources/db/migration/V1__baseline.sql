CREATE FUNCTION enforce_must_change_password() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
  IF OLD.must_change_password
     AND NEW.must_change_password = false
     AND NEW.password_hash IS NOT DISTINCT FROM OLD.password_hash THEN
    RAISE EXCEPTION '该账号处于「待本人设置密码」状态，必须同时更新密码才能解除';
  END IF;
  RETURN NEW;
END;
$$;

